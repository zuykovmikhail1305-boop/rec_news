"""Создаёт SQLite-базу ``news.db`` с 20 псевдо-новостями для тестов дедупликации.

Состав:
* 10 оригинальных новостей;
* для двух из них — по одной почти полной копии (``near_duplicate``)
  и по одной семантически похожей копии (``semantic_duplicate``);
* 6 новостей — логические продолжения других (``continuation``),
  включая цепочку из двух продолжений.

Сами новости лежат в таблице ``news``. Эталонная разметка связей лежит
в отдельной таблице ``news_relations``, чтобы проверять, правильно ли
алгоритм находит дубликаты и продолжения.
"""

from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

DB_PATH = Path(__file__).with_name("news.db")

SCHEMA = """
CREATE TABLE news (
    document_id      TEXT PRIMARY KEY,
    title            TEXT,
    first_paragraph  TEXT,
    full_text        TEXT NOT NULL,
    publication_time TEXT NOT NULL,
    event_type       TEXT NOT NULL,
    url              TEXT,
    created_at       TEXT NOT NULL
);
CREATE TABLE news_relations (
    document_id TEXT PRIMARY KEY REFERENCES news(document_id),
    relation    TEXT NOT NULL CHECK (relation IN (
                    'original', 'near_duplicate', 'semantic_duplicate', 'continuation'
                )),
    related_to  TEXT REFERENCES news(document_id)
);
CREATE INDEX idx_news_relations_related_to ON news_relations(related_to);
"""


@dataclass(frozen=True)
class SeedNews:
    """Новость для заполнения базы; ``key`` нужен только для связей."""

    key: str
    title: str
    first_paragraph: str
    body: tuple[str, ...]
    url: str
    publication_time: str
    event_type: str
    relation: str = "original"
    related_key: str | None = None

    @property
    def full_text(self) -> str:
        return "\n\n".join((self.first_paragraph, *self.body))


