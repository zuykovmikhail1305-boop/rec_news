def build(db_path: Path = DB_PATH) -> None:
    if db_path.exists():
        db_path.unlink()

    # document_id назначаются по времени публикации, чтобы связанные новости не шли подряд
    rows = sorted(NEWS, key=lambda item: item.publication_time)
    key_to_id = {item.key: f"news_{idx:03d}" for idx, item in enumerate(rows, start=1)}
    created_at = datetime.now(timezone.utc).isoformat(timespec="seconds")

    with sqlite3.connect(db_path) as conn:
        conn.executescript(SCHEMA)
        conn.executemany(
            "INSERT INTO news (document_id, title, first_paragraph, full_text, publication_time, "
            "event_type, url, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            [
                (
                    key_to_id[item.key],
                    item.title,
                    item.first_paragraph,
                    item.full_text,
                    item.publication_time,
                    item.event_type,
                    item.url,
                    created_at,
                )
                for item in rows
            ],
        )
        conn.executemany(
            "INSERT INTO news_relations (document_id, relation, related_to) VALUES (?, ?, ?)",
            [
                (
                    key_to_id[item.key],
                    item.relation,
                    key_to_id[item.related_key] if item.related_key else None,
                )
                for item in rows
            ],
        )


if __name__ == "__main__":
    build()
    print(f"Создана база {DB_PATH} ({len(NEWS)} новостей)")
