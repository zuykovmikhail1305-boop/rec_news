@dataclass(frozen=True)
class SeedNews:
    """Новость для заполнения базы; ``key`` нужен только для связей."""

    key: str
    title: str
    text: str
    url: str
    publication_time: str
    relation: str = "original"
    related_key: str | None = None

    def to_stored(
        self,
        document_id: str,
        created_at: str,
        related_to: str | None = None,
    ) -> StoredNews:
        """Превращает тестовую новость в запись хранилища."""
        return StoredNews(
            document_id=document_id,
            text=self.text,
            metadata={
                "title": self.title,
                "url": self.url,
                "source": urlparse(self.url).netloc,
                "publication_time": self.publication_time,
                "created_at": created_at,
                "test": {"relation": self.relation, "related_to": related_to},
            },
        )


def paragraphs(*parts: str) -> str:
    """Склеивает абзацы новости через пустую строку."""
    return "\n\n".join(parts)


def near_copy(text: str, replacements: Sequence[tuple[str, str]]) -> str:
    """Почти полная копия: та же новость с мелкими правками оформления.

    Каждая замена обязана встретиться в тексте — так фикстура не сломается
    молча, если оригинал отредактируют.
    """
    for old, new in replacements:
        if old not in text:
            raise ValueError(f"Фрагмент {old!r} не найден в тексте оригинала.")
        text = text.replace(old, new)
    return text


