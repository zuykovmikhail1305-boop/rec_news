def build(db_path: Path = DB_PATH) -> None:
    if db_path.exists():
        db_path.unlink()

    # id назначаются по времени публикации, чтобы связанные новости не шли подряд
    rows = sorted(NEWS, key=lambda item: item[4])
    key_to_id = {item[0]: idx for idx, item in enumerate(rows, start=1)}

    with sqlite3.connect(db_path) as conn:
        conn.executescript(SCHEMA)
        conn.executemany(
            "INSERT INTO news (id, title, text, source, time_published, type_event, relation, related_to) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            [
                (
                    key_to_id[key],
                    title,
                    text,
                    source,
                    published,
                    type_event,
                    relation,
                    key_to_id[related] if related else None,
                )
                for key, title, text, source, published, type_event, relation, related in rows
            ],
        )


if __name__ == "__main__":
    build()
    print(f"Создана база {DB_PATH} ({len(NEWS)} новостей)")
